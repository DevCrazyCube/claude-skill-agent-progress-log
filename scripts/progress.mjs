#!/usr/bin/env node
// An append-only progress log for a repo that several agents (and people) work in.
//
// Every session adds ONE new file to progress/. PROGRESS.md is generated from those files and never edited by
// hand, so two sessions writing at the same moment make two files, never a merge conflict.
//
//   node progress.mjs                     regenerate PROGRESS.md from progress/*.md
//   node progress.mjs new --agent claude --milestone M1 [--done] [--tests green] [--lint red]
//                                         write a new fragment with the current UTC time, print its path
//   node progress.mjs --check             exit 1 when PROGRESS.md is stale or a fragment is malformed (for CI)
//
// Settings come from progress.config.json in the working directory (all optional):
//   { "title": "My project", "dir": "progress", "out": "PROGRESS.md",
//     "milestones": [{ "id": "M0", "name": "Skeleton", "demo": "what you can show when it is done" }],
//     "checks": ["tests", "lint"] }
// No dependencies; Node 18 or newer.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const CHECK_VALUES = ['green', 'red', 'not-applicable']

export function loadConfig(cwd = '.') {
  const file = join(cwd, 'progress.config.json')
  const given = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {}
  return {
    title: given.title || 'Progress',
    dir: given.dir || 'progress',
    out: given.out || 'PROGRESS.md',
    milestones: given.milestones || [],
    checks: given.checks || [],
  }
}

export function parse(raw, file) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/)
  if (!m) return { meta: {}, body: raw.trim(), file }
  const meta = {}
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([\w-]+):\s*(.*?)\s*(?:#.*)?$/)
    if (kv) meta[kv[1]] = kv[2]
  }
  return { meta, body: m[2].trim(), file }
}

export function readEntries(config, cwd = '.') {
  const dir = join(cwd, config.dir)
  if (!existsSync(dir)) return []
  return readdirSync(dir).filter(f => f.endsWith('.md')).sort().reverse()
    .map(f => parse(readFileSync(join(dir, f), 'utf8'), f))
}

/** What is wrong with the fragments, as a list of sentences. Empty when all is well. */
export function problems(entries, config) {
  const out = []
  const ids = new Set(config.milestones.map(m => m.id))
  for (const e of entries) {
    if (!e.meta.at) out.push(`${e.file}: no "at:" in the front matter`)
    if (!e.meta.agent) out.push(`${e.file}: no "agent:" in the front matter`)
    if (ids.size && e.meta.milestone && !ids.has(e.meta.milestone)) out.push(`${e.file}: unknown milestone "${e.meta.milestone}"`)
    for (const c of config.checks) {
      const v = e.meta[c]
      if (v === undefined) out.push(`${e.file}: check "${c}" is not stated (green, red or not-applicable)`)
      else if (!CHECK_VALUES.includes(v)) out.push(`${e.file}: check "${c}" is "${v}", expected green, red or not-applicable`)
    }
    for (const name of ['Did', 'Next']) {
      const v = field(e.body, name)
      if (v === null) out.push(`${e.file}: no **${name}:** line`)
      else if (!v) out.push(`${e.file}: **${name}:** is empty`) // a fragment from "new" that nobody filled in
    }
  }
  return out
}

const mark = v => (v === 'green' ? '🟢 green' : v === 'red' ? '🔴 red' : '—')
/** The text after **Name:** up to the next **Label:** or the end. '' when it is empty, null when the line is missing. */
function field(body, name) {
  // [ \t]* and not \s*: \s* would run past an empty value's line end and return the next label's line as this value
  const m = body.match(new RegExp(`\\*\\*${name}:\\*\\*[ \\t]*([\\s\\S]*?)(?=\\r?\\n\\*\\*|$)`))
  return m ? m[1].trim() : null
}

/** A milestone is done when its newest fragment says so AND none of that fragment's checks is red. */
export function milestoneState(entry, config) {
  if (!entry) return 'not started'
  const red = config.checks.some(c => entry.meta[c] === 'red')
  if (entry.meta.done === 'true' && !red) return '✅ done'
  if (entry.meta.done === 'true' && red) return 'in progress (a check is red)'
  return 'in progress'
}

export function render(entries, config) {
  const latest = entries[0]
  const newestPer = new Map() // entries are newest first, so keep the first one seen per milestone
  for (const e of entries) if (e.meta.milestone && !newestPer.has(e.meta.milestone)) newestPer.set(e.meta.milestone, e)

  const L = []
  L.push(`# ${config.title}: progress`, '')
  L.push('<!-- GENERATED by progress.mjs. Do not edit by hand:', `     add a file to ${config.dir}/ and run the script again. -->`, '')
  L.push('## Now', '')
  if (latest) {
    L.push(`**Milestone:** ${latest.meta.milestone || '—'} · **last touched by:** ${latest.meta.agent || '—'} · ${latest.meta.at || '—'}`, '')
    L.push(`**Next action:** ${field(latest.body, 'Next') || '—'}`, '')
    L.push(`**Blocked on:** ${field(latest.body, 'Blockers') || 'nothing'}`)
  } else {
    L.push('Nothing logged yet. Add the first fragment with `node progress.mjs new --agent <name>`.')
  }
  L.push('')
  if (config.milestones.length) {
    L.push('## Milestones', '')
    L.push(`| | Name | Demo | State |${config.checks.map(c => ` ${c} |`).join('')}`)
    L.push(`|---|---|---|---|${config.checks.map(() => '---|').join('')}`)
    for (const m of config.milestones) {
      const e = newestPer.get(m.id)
      L.push(`| ${m.id} | ${m.name} | ${m.demo || ''} | ${milestoneState(e, config)} |${config.checks.map(c => ` ${mark(e?.meta[c])} |`).join('')}`)
    }
    L.push('')
  }
  L.push('## Log', '', `${entries.length} ${entries.length === 1 ? 'entry' : 'entries'}, newest first.`, '')
  for (const e of entries) {
    // a blank line before each **Label:** so Markdown shows them as separate lines, not one run-on paragraph
    L.push(`### ${e.meta.at || e.file} · ${e.meta.agent || '?'} · ${e.meta.milestone || '—'}`, '', e.body.replace(/\r?\n(?=\*\*)/g, '\n\n'), '')
    const stated = config.checks.filter(c => mark(e.meta[c]) !== '—')
    if (stated.length) L.push(`*${stated.map(c => `${c}: ${mark(e.meta[c])}`).join(' · ')}*`, '')
  }
  return L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

export function newFragment(args, config, cwd = '.', now = new Date()) {
  const opt = {}
  for (let i = 0; i < args.length; i++) {
    if (!args[i].startsWith('--')) throw new Error(`unexpected argument "${args[i]}"`)
    const key = args[i].slice(2)
    if (key === 'done') opt.done = 'true'
    else opt[key] = args[++i]
  }
  if (!opt.agent || !/^[\w-]+$/.test(opt.agent)) throw new Error('give --agent <name> (letters, digits, - and _)')
  for (const c of config.checks) {
    if (opt[c] !== undefined && !CHECK_VALUES.includes(opt[c])) throw new Error(`--${c} must be green, red or not-applicable`)
  }
  const at = now.toISOString().replace(/\.\d+Z$/, 'Z')
  const stamp = at.replace(/[-:]/g, '')
  const dir = join(cwd, config.dir)
  mkdirSync(dir, { recursive: true })
  let file = join(dir, `${stamp}-${opt.agent}.md`)
  for (let n = 2; existsSync(file); n++) file = join(dir, `${stamp}-${opt.agent}-${n}.md`) // never overwrite
  const head = [`at: ${at}`, `agent: ${opt.agent}`]
  if (opt.milestone) head.push(`milestone: ${opt.milestone}`)
  if (opt.done) head.push('done: true')
  for (const c of config.checks) head.push(`${c}: ${opt[c] || 'not-applicable'}`)
  const body = ['**Did:** ', '**Next:** ', '**Blockers:** nothing']
  writeFileSync(file, `---\n${head.join('\n')}\n---\n\n${body.join('\n')}\n`, { flag: 'wx' })
  return file
}

function main(argv) {
  const config = loadConfig()
  if (argv[0] === 'new') {
    console.log(newFragment(argv.slice(1), config))
    return 0
  }
  const entries = readEntries(config)
  const text = render(entries, config)
  const wrong = problems(entries, config)
  for (const p of wrong) console.error(`warning: ${p}`)
  if (argv.includes('--check')) {
    const current = existsSync(config.out) ? readFileSync(config.out, 'utf8') : ''
    if (current !== text) console.error(`${config.out} is stale: run "node progress.mjs" and commit the result`)
    return current !== text || wrong.length ? 1 : 0
  }
  writeFileSync(config.out, text)
  console.log(`${config.out} ← ${entries.length} fragment(s)`)
  return 0
}

